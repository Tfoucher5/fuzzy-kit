// Measures what each built-in language pack reads, on the same cases for
// every language, and writes the table shown in the docs
// (docs/.vitepress/language-coverage.md, included in "Languages and presets").
// Run after changing a pack: npm run languages:coverage (tests fail if the table is stale).
import { writeFileSync } from 'node:fs';
import { normalize } from '../dist/esm/index.js';
import de from '../dist/esm/lang/de.js';
import en from '../dist/esm/lang/en.js';
import es from '../dist/esm/lang/es.js';
import fr from '../dist/esm/lang/fr.js';
import it from '../dist/esm/lang/it.js';
import nl from '../dist/esm/lang/nl.js';

/** Inputs for each feature below, in each language. */
export const NUMBER_CASES = {
  en: ['seventeen', 'forty five', 'one hundred', 'three hundred forty two', 'one thousand', 'two thousand twenty five', 'second', 'twenty first'],
  fr: ['dix-sept', 'quarante-cinq', 'cent', 'trois cent quarante-deux', 'mille', 'deux mille vingt-cinq', 'deuxième', 'vingt et unième'],
  es: ['diecisiete', 'cuarenta y cinco', 'cien', 'trescientos cuarenta y dos', 'mil', 'dos mil veinticinco', 'segundo', 'vigésimo primero'],
  de: ['siebzehn', 'fünfundvierzig', 'hundert', 'dreihundertzweiundvierzig', 'tausend', 'zweitausendfünfundzwanzig', 'zweite', 'einundzwanzigste'],
  it: ['diciassette', 'quarantacinque', 'cento', 'trecentoquarantadue', 'mille', 'duemilaventicinque', 'secondo', 'ventunesimo'],
  nl: ['zeventien', 'vijfenveertig', 'honderd', 'driehonderdtweeënveertig', 'duizend', 'tweeduizendvijfentwintig', 'tweede', 'eenentwintigste'],
};
const EXPECTED = ['17', '45', '100', '342', '1000', '2025', '2', '21'];
export const FEATURES = ['0 to 19', '20 to 99', '100', '101 to 999', 'thousands', 'years (2025)', 'ordinals (2nd)', 'ordinals (21st)'];

const PACKS = { en, fr, es, de, it, nl };

/** True when the words became the expected number (an ordinal mark like 2nd or 2º is fine). */
function reads(pack, input, expected) {
  const out = normalize(input, { languages: [pack] });
  return out.replace(/[^\d]/g, '') === expected && !/[a-z]{3,}/.test(out);
}

export function coverage() {
  return Object.entries(PACKS).map(([code, pack]) => ({
    code,
    name: pack.name,
    numbers: NUMBER_CASES[code].map((input, i) => reads(pack, input, EXPECTED[i])),
    articles: pack.articles?.length ?? 0,
    stopwords: pack.stopwords?.length ?? 0,
    phonetic: pack.phonetic?.length ?? 0,
  }));
}

export function markdown() {
  return `<!-- Generated by scripts/language-coverage.mjs: do not edit. -->

${table(coverage())}
`;
}

function table(rows) {
  const yes = '✅';
  const no = '—';
  const lines = [
    `| | ${rows.map((r) => r.name).join(' | ')} |`,
    `| --- | ${rows.map(() => ':---:').join(' | ')} |`,
    ...FEATURES.map((f, i) => `| Numbers: ${f} | ${rows.map((r) => (r.numbers[i] ? yes : no)).join(' | ')} |`),
    `| Articles | ${rows.map((r) => r.articles).join(' | ')} |`,
    `| Stop words | ${rows.map((r) => r.stopwords).join(' | ')} |`,
    `| Sound rules | ${rows.map((r) => r.phonetic).join(' | ')} |`,
  ];
  return lines.join('\n');
}

if (process.argv[1]?.endsWith('language-coverage.mjs')) {
  writeFileSync(new URL('../docs/.vitepress/language-coverage.md', import.meta.url), markdown());
}
